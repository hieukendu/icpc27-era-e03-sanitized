"""Build a deterministic anonymous package from an explicit allowlist."""
from pathlib import Path
import argparse,hashlib,json,shutil,zipfile
ROOT=Path(__file__).resolve().parents[2]
VERIFY='''from pathlib import Path
import hashlib,json,sys
root=Path(__file__).resolve().parent
manifest=json.loads((root/'MANIFEST.json').read_text())
bad=[name for name,h in manifest['files_sha256'].items() if not (root/name).is_file() or hashlib.sha256((root/name).read_bytes()).hexdigest()!=h]
print('Files verified:',len(manifest['files_sha256']),'mismatches:',bad)
sys.exit(bool(bad))
'''
README='''# E03-scoped-v1 replication package

What Evidence Supports an AI Code Explanation? A Retrospective Study of Slot and Sentence Scope.

Release status: {status}. The checker is frozen v6.1; current-corpus results are retrospective. All semantic audits and corrected slots are tentative assistant coding. Independent human validation and participant outcomes are pending.

1. Verify the frozen download: `python3 verify_release.py`.
2. Open `artifact/README.md` for pinned installation requirements.
3. From `artifact/`, run `make replay` (or set `PY` to a Python environment with the pinned dependencies).

Replay regenerates all paper analyses, figures/tables and the PDF from frozen observations, with no model calls or generated code execution. The separate `make simulate` command fits the actual crossed logistic design. Simulation outputs are synthetic, not participant outcomes.

The manifest records SHA-256 for every included file. Download/replay verification should precede any claim that public anonymous hosting is complete. Upstream licenses are in `artifact/licenses`, and icon attribution is in `manuscript/figures/icons/SOURCES.md`.
'''
def selected():
 for name in ['artifact/src','artifact/tests','artifact/docs','artifact/licenses','artifact/data','artifact/results',
              'manuscript/sections','manuscript/generated','manuscript/figures']:
  for p in sorted((ROOT/name).rglob('*')):
   rel=p.relative_to(ROOT)
   if not p.is_file() or p.is_symlink():continue
   if any(x in rel.parts for x in ['repos','__pycache__','.git','build']):continue
   if p.suffix in ['.log','.pyc','.bak'] or p.name=='.DS_Store':continue
   if 'simulation' in rel.parts and (p.name.endswith('_3.rds') or p.name.endswith('_3.csv') or p.name=='power_3.csv'):continue
   yield p
 for name in ['artifact/README.md','artifact/Makefile','artifact/requirements.txt','manuscript/main.tex','manuscript/main.pdf','manuscript/references.bib']:
  yield ROOT/name

def main():
 ap=argparse.ArgumentParser();ap.add_argument('--candidate',action='store_true');a=ap.parse_args()
 if not a.candidate:
  if not (ROOT/'artifact/results/revision/simulation/power_1000.csv').exists():raise SystemExit('Full simulation missing')
 target=ROOT/'release/E03-scoped-v1';target.mkdir(parents=True,exist_ok=True)
 paths=list(selected());payload={str(p.relative_to(ROOT)):p.read_bytes() for p in paths}
 payload['README.md']=README.format(status='candidate; validation still in progress' if a.candidate else 'frozen local package; hosting status recorded separately').encode()
 payload['verify_release.py']=VERIFY.encode()
 # Remove only stale files previously generated by this builder, never git metadata.
 old=target/'MANIFEST.json'
 if old.exists():
  for name in json.loads(old.read_text()).get('files_sha256',{}):
   if name not in payload and (target/name).is_file():(target/name).unlink()
 for name,data in payload.items():
  dest=target/name;dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(data)
 bad=[]
 for name,data in payload.items():
  if name.endswith(('.pdf','.rds')):continue
  low=data.lower()
  for term in [b'/users/',b'gho_',b'ghp_',b'sk-ant-']:
   # This script lists scan terms, so exclude its own literal term list from identity check.
   if term in low and name!='artifact/src/build_release.py':bad.append(name)
 if bad:raise SystemExit('Anonymity scan flagged: '+str(sorted(set(bad))))
 manifest={'release':'E03-scoped-v1','engine':'v6.1','candidate':a.candidate,
   'files_sha256':{n:hashlib.sha256(d).hexdigest() for n,d in sorted(payload.items())}}
 (target/'MANIFEST.json').write_text(json.dumps(manifest,sort_keys=True,indent=2)+'\n')
 zip_path=target.parent/'E03-scoped-v1.zip'
 with zipfile.ZipFile(zip_path,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
  for name in sorted(list(payload)+['MANIFEST.json']):
   info=zipfile.ZipInfo('E03-scoped-v1/'+name,date_time=(2026,11,11,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED;info.external_attr=0o644<<16
   z.writestr(info,(target/name).read_bytes())
 digest=hashlib.sha256(zip_path.read_bytes()).hexdigest()
 zip_path.with_suffix('.zip.sha256').write_text(digest+'  '+zip_path.name+'\n')
 print('Built',zip_path.name,'files',len(payload),'bytes',zip_path.stat().st_size,'SHA256',digest)
if __name__=='__main__':main()
